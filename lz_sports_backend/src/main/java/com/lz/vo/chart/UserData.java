package com.lz.vo.chart;

public class UserData {
    private String date;
    private int addUser;
    private int addAthlete;

    public String getDate() {
        return date;
    }

    public void setDate(String date) {
        this.date = date;
    }

    public int getAddUser() {
        return addUser;
    }

    public void setAddUser(int addUser) {
        this.addUser = addUser;
    }

    public int getAddAthlete() {
        return addAthlete;
    }

    public void setAddAthlete(int addAthlete) {
        this.addAthlete = addAthlete;
    }
}
