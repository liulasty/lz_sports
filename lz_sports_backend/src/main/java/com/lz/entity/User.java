    private Long id;

    @TableField("username")
    private String username;

    @TableField("password")
    private String password;

    @TableField("name")
    private String name;

    @TableField("gender")
    private String gender;

    @TableField("student_id")
    private String studentId;

    @TableField("grade_id")
    private Long gradeId;

    @TableField("email")
    private String email;

    @TableField("role")
    private UserRole userType;

